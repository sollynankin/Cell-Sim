export function partsOf(P) {
  P.flagellaCount = P.flagella.length;
  return PARTS.filter((p) => p.has(P)).map((p) => ({
    name: p.name, color: p.color, level: p.level(P),
    what: typeof p.what === 'function' ? p.what(P) : p.what, cost: p.cost,
  }));
}

